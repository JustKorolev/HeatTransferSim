def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="docs/user_guide/images")
    parser.add_argument("--scale", type=int, default=2, help="device pixels per logical pixel")
    parser.add_argument(
        "--with-viewer",
        action="store_true",
        help="use a real display so the VTK 3D view can be captured too",
    )
    args = parser.parse_args()

    out_dir = Path(args.out)
    app = QtWidgets.QApplication.instance() or QtWidgets.QApplication([])
    _ = app
    family = install_fonts()
    if not family:
        print(
            "error: no usable font was found, and the offscreen platform has none of "
            "its own -- every glyph would render as an empty box.",
            file=sys.stderr,
        )
        return 1
    print(f"font: {family}")

    written: list[Path] = []
    panels: dict[str, tuple[SimulationControlsPanel, QtWidgets.QWidget]] = {}
    for filename, mode, section_key, rows in SHOTS:
        if mode not in panels:
            panels[mode] = build_panel(mode)
        panel, host = panels[mode]
        print(f"{filename} ({mode} / {section_key})")
        path = shoot_section(panel, host, section_key, rows, out_dir / filename, args.scale)
        if path is not None:
            written.append(path)

    print("help_search.png")
    path = shoot_help_dialog(out_dir / "help_search.png", args.scale)
    if path is not None:
        written.append(path)
    print("help_tutorials.png")
    path = shoot_tutorials_dialog(out_dir / "help_tutorials.png", args.scale)
    if path is not None:
        written.append(path)

    print(f"\nWrote {len(written)} image(s) to {out_dir}:")
    for path in written:
        print(f"  {path.name:28} {path.stat().st_size // 1024:5} KB")
    if not args.with_viewer:
        print(
            "\nThe 3D octree view is not included: VTK needs a real OpenGL context. "
            "Re-run with --with-viewer on a machine with a display to add it."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
